                <td style="width: 50%; text-align: justify; vertical-align: top; padding: 10px;">
                    Application for any type of leave shall be made on this Form and to be accomplished at least in
                    duplicate with documentary requirements, as follows:
                    <br><br>
                    <b>1. Vacation leave*</b><br>
                    It shall be filed (5) days in advance, whenever possible, of the effective date of such leave.
                    Vacation leave within in the Philippines or abroad shall be indicated in the form for purposes of
                    securing travel authority and completing clearance from money and work accountabilities.

                    <br><br>

                    <b>2. Mandatory/Forced leave*</b><br>
                    Annual five-day vacation leave shall be forfeited if not taken during the year. In case the
                    scheduled leave has been cancelled in the exigency of the service by the head of agency, it shall no
                    longer be deducted from the accumulated vacation leave. Availment of one (1) day or more Vacation
                    Leave (VL) shall be considered for complying the mandatory/forced leave subject to the conditions
                    under Section 25, Rule XVI of the Omnibus Rules implementing E.O. No. 292.
                    <br><br>

                    <b>3. Sick leave*</b><br>
                    <ul>
                        <li>It shall be filed immediately upon employee's return from such leave.</li>
                        <li>If filed in advance or exceeding five (5) days, application shall be accompanied by a
                            medical certificate. In case medical consultation was not availed of, an affidavit should be
                            executed by an applicant.</li>
                    </ul>

                    <b>4. Maternity leave* - 105 days</b><br>
                    <ul>
                        <li>Proof of pregnancy e.g. ultrasound, doctor's certificate on the expected date of delivery
                        </li>
                        <li>Acomplished Notice of Allocation of Maternity Leave Credits (CS Form No. 6a), if needed</li>
                        <li>Seconded female employees shall enjoy maternity leave with full pay in the recipient agency.
                        </li>
                    </ul>

                    <b>5. Paternity leave* - 7 days</b><br>
                    Proof of child's delivery e.g. birth certificate, medical certificate and marriage contract

                    <br><br>

                    <b>6. Special Privilege leave</b><br>
                    It shall be filed/approved for at least one (1) week prior to availment, except on emergency cases.
                    Special privilege leave within the Philippines or abroad shall be indicated in the form for purposes
                    os securing travel authority and completing clearance from money and work accountabilities.

                    <br><br>

                    <b>7. Solo Parent leave* - 7 days</b><br>
                    It shall be filed in advance or whenever possible five (5) days before going on such leave with
                    updated Solo Parent Identification Card.

                    <br><br>

                    <b>8. Study leave* - up to 6 months</b><br>
                    <ul>
                        <li>Shall meet the agency's internal requirements, if any;</li>
                        <li>Contract between the agency head or authorized representative and the employee concerned.
                        </li>
                    </ul>

                    <b>9. VAWC leave - 10 days</b><br>
                    <ul>
                        <li>It shall be filed in advance or immediately upon the woman employee's return from such
                            leave.</li>
                        <li>It shall be accompanied by any of the following supporting documents:
                            <ol type="a">
                                <li>Barangay Protection Order (BPO) obtained from the barangay;</li>
                                <li>Temporary/Permanent Protection Order (TPO/PPO) obtained from the court;</li>
                                <li>If the protection order is not yet issued by the barangay or the court, a
                                    certification issued by the Punong Barangay/Kagawad or Prosecutor or the Clerk of
                                    Court that the application for the BPO, TPO or PPO has been filed with the said
                                    office shall be sufficient to support the application for the ten-day leave; or</li>
                            </ol>
                        </li>
                    </ul>
                </td>

                <td style="width: 50%; text-align: justify; vertical-align: top; padding: 10px;">
                    <ol type="a" start="4" style="margin-left: 20px;">
                        <li>
                            In the absence of the BPO/TPO/PPO or the certification, a police report specifying the
                            details of the occurrence of violence on the victim and a medical certificate may be
                            considered, at
                            the discretion of the immediate supervisor of the woman employee concerned.
                        </li>
                    </ol>

                    <b>10. Rehabilitation leave* - up to 6 months</b><br>
                    <ul>
                        <li>Application shall be made within one (1) week from the time of the accident except when a
                            longer period is warranted.</li>
                        <li>Letter request supported by relevant reports such as the police report, if any,</li>
                        <li>Medical certificate on the nature of the injuries, the course of treatment involved, and the
                            need to undergo rest, recuperation, and rehabilitation, as the case may be.</li>
                        <li>Written concurrence of a government physician should be obtained relative to the
                            recommendation for rehabilitation if the attending physician is a private practitioner,
                            particularly on the duration of the period of rehabilitation.</li>
                    </ul>

                    <b>11. Special leave benefits for women* - up to 2 months</b><br>
                    <ul>
                        <li>The application may be filed in advance, that is, at least five (5) days prior to the
                            scheduled date of the gynecological surgery that will be undergone by the employee. In case
                            of emergency, the application for special leave shall be filed immediately upon employee's
                            return but during confinement the agency shall be notified of said surgery.</li>
                        <li>The application shall be accompanied by a medical certiticate filed out by the proper
                            medical authorities, e.g. the attending surgeon accompanied by a clnical summary reflecting
                            the gynecological disorder which shall be addressed or was addressed by the said surgery;
                            the histopathological repor; the operative technique used for the surgery; the duration of
                            the surgery including the perioperative period (period of confinement around surgery); as
                            well as the employee's estimated period of recuperation for the same.</li>
                    </ul>

                    <b>12. Special Emergency (Calamity) leave - up to 5 days</b><br>
                    <ul>
                        <li>The special emergency leave can be applied for a maximum of five (5) days straight working
                            days or staggered basis within thirty (30) days from the actual occurence of the natural
                            calamity/disaster. Said privilege shall be enjoyed once a year, not in every instance of
                            calamity or disaster.</li>
                        <li>The head of office shall take full responsibility for the grant of special emergency leave
                            and verification of the employee's eligibility to be granted thereof. Said verification
                            shall include: validation of place of residence based on latest available records of the
                            affected employee; verification that the place of residence is covered in the declaration of
                            calamity area by the proper government agency; and such other proods as may be necessary.
                        </li>
                    </ul>

                    <b>13. Monetization of leave credits</b><br>
                    Application for monetization of fifty percent (50%) or more of the accumulated leave credits shall
                    be accompanied by letter request to the head of the agency stating the valid and justifiable
                    reasons.

                    <br><br>

                    <b>14. Terminal leave*</b><br>
                    Proof of employee's resignation or retirement or separation from the service.

                    <br><br>

                    <b>15. Adoption leave</b>
                    <ul>
                        <li>Application for adoption leave shall be filed with an authenticated copy of the Pre-Adoptive
                            Placement Authority issued by the Department of Social Welfare and Development (DSWD).</li>
                    </ul>


                </td>
            </tr>
